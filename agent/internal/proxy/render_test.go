func TestRenderConfigValidatesAndFormats3Proxy(t *testing.T) {
	endpoints := []controller.ProxyEndpointConfig{
		{
			ID:         "ep-http-1",
			Protocol:   "http",
			ListenIP:   "10.77.0.11",
			ListenPort: 20001,
			Username:   "testuser",
			Password:   "testpass",
			Enabled:    true,
		},
		{
			ID:         "ep-socks-1",
			Protocol:   "socks5",
			ListenIP:   "10.77.0.11",
			ListenPort: 30001,
			Username:   "socksuser",
			Password:   "sockspass",
			Enabled:    true,
		},
	}

	cfg, digest, err := proxy.RenderConfig(endpoints, nil)
	if err != nil {
		t.Fatalf("RenderConfig failed: %v", err)
	}

	if digest == "" {
		t.Errorf("Expected non-empty digest")
	}

	if !strings.Contains(cfg, "users testuser:CL:testpass") {
		t.Errorf("Expected testuser authentication line, got: %s", cfg)
	}

	if !strings.Contains(cfg, "proxy -p20001 -i10.77.0.11") {
		t.Errorf("Expected http proxy directive, got: %s", cfg)
	}

	if !strings.Contains(cfg, "socks -p30001 -i10.77.0.11") {
		t.Errorf("Expected socks proxy directive, got: %s", cfg)
	}

	// CRLF injection attempt must fail
	malicious := []controller.ProxyEndpointConfig{
		{
			ID:         "ep-bad",
			Protocol:   "http",
			ListenIP:   "10.77.0.11\nmalicious directive",
			ListenPort: 20002,
			Username:   "user",
			Password:   "pass",
			Enabled:    true,
		},
	}
	_, _, err = proxy.RenderConfig(malicious, nil)
	if err == nil {
		t.Errorf("Expected CRLF injection error, got nil")
	}
}

func TestRenderConfigEmptyEndpoints(t *testing.T) {
	cfg, digest, err := proxy.RenderConfig([]controller.ProxyEndpointConfig{}, nil)
	if err != nil {
		t.Fatalf("RenderConfig failed for empty endpoints: %v", err)
	}
	if digest == "" {
		t.Errorf("Expected non-empty digest for empty config")
	}
	if !strings.Contains(cfg, "# Generated by proxyfleet-agent.") {
		t.Errorf("Expected header in rendered config")
	}
	if strings.Contains(cfg, "users") {
		t.Errorf("Expected no users directive in empty config")
	}
	if strings.Contains(cfg, "proxy ") || strings.Contains(cfg, "socks ") {
		t.Errorf("Expected no proxy directives in empty config")
	}
}

func TestRenderConfigWithCapacityCeiling(t *testing.T) {
	endpoints := []controller.ProxyEndpointConfig{
		{
			ID:         "ep-http-1",
			Protocol:   "http",
			ListenIP:   "10.77.0.11",
			ListenPort: 20001,
			Username:   "testuser",
			Password:   "testpass",
			Enabled:    true,
		},
		{
			ID:         "ep-socks-1",
			Protocol:   "socks5",
			ListenIP:   "10.77.0.11",
			ListenPort: 30001,
			Username:   "socksuser",
			Password:   "sockspass",
			Enabled:    true,
		},
	}

	maxConn := 250
	capacity := &controller.FleetCapacitySettings{
		MaxConnections: &maxConn,
	}

	cfg, _, err := proxy.RenderConfig(endpoints, capacity)
	if err != nil {
		t.Fatalf("RenderConfig with capacity failed: %v", err)
	}

	// Verify maxconn emitted per listener scope
	if !strings.Contains(cfg, "maxconn 250\nproxy -p20001") {
		t.Errorf("expected maxconn 250 preceding proxy command, got: %s", cfg)
	}
	if !strings.Contains(cfg, "maxconn 250\nsocks -p30001") {
		t.Errorf("expected maxconn 250 preceding socks command, got: %s", cfg)
	}

	// Nil capacity must NOT emit blanket default maxconn
	cfgNoCap, _, err := proxy.RenderConfig(endpoints, nil)
	if err != nil {
		t.Fatalf("RenderConfig without capacity failed: %v", err)
	}
	if strings.Contains(cfgNoCap, "maxconn") {
		t.Errorf("expected no maxconn line when capacity is nil, got: %s", cfgNoCap)
	}

	// Zero or negative maxConnections must fail
	zeroConn := 0
	_, _, err = proxy.RenderConfig(endpoints, &controller.FleetCapacitySettings{MaxConnections: &zeroConn})
	if err == nil {
		t.Errorf("expected error for maxConnections=0, got nil")
	}

	negConn := -10
	_, _, err = proxy.RenderConfig(endpoints, &controller.FleetCapacitySettings{MaxConnections: &negConn})
	if err == nil {
		t.Errorf("expected error for maxConnections=-10, got nil")
	}
}

func TestRenderConfigDoesNotEchoPasswordOnError(t *testing.T) {
	sensitivePass := "superSecretP@ss123\nInjectedLine"
	endpoints := []controller.ProxyEndpointConfig{
		{
			ID:         "ep-bad-pass",
			Protocol:   "http",
			ListenIP:   "10.77.0.11",
			ListenPort: 20001,
			Username:   "alice",
			Password:   sensitivePass,
			Enabled:    true,
		},
	}

	_, _, err := proxy.RenderConfig(endpoints, nil)
	if err == nil {
		t.Fatalf("expected error for newline in password, got nil")
	}
	if strings.Contains(err.Error(), "superSecretP@ss123") {
		t.Errorf("security violation: password was echoed in error string: %v", err)
	}
}
